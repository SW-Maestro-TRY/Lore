-- refresh 토큰에 <b>절대 만료 상한</b>을 더한다.
--
-- ★ 왜 — 지금은 회전할 때마다 expiresAt 이 14일 뒤로 밀린다(슬라이딩). 그래서 매일 쓰는
--   사용자는 재로그인 없이 영원히 로그인 상태가 유지된다. 최초 로그인 시점부터의 상한(기본 90일)을
--   하나 더 두어, 상한이 지나면 활동 중이어도 반드시 다시 로그인하게 만든다(보안 백스톱).
--
-- ★ 동작 — 로그인은 이 값을 now+90일로 새로 찍고, 회전은 옛 토큰 값을 <b>물려받기만</b> 한다
--   (다시 90일을 주지 않는다). expiresAt 은 슬라이딩 만료와 이 값 중 이른 쪽으로 깎이므로,
--   상한이 지나면 expiresAt 도 그 이전이 되어 회전이 자연히 거부된다.
--
-- ★ nullable — 이 마이그레이션 이전에 발급된 기존 행은 값이 없다. NULL 은 "상한 없음" 으로
--   관대하게 다뤄(코드의 isUsable 이 NULL 을 통과시킨다) 기존 로그인·회전이 깨지지 않게 한다.
--   새 로그인부터 값이 채워진다.
ALTER TABLE user_refresh_token
    ADD COLUMN absolute_expires_at timestamp(6) with time zone;
