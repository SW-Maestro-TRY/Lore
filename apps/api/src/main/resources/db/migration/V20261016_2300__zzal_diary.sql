-- One immutable fictional diary + generation receipt per opportunity. No production execution approval.
ALTER TABLE zzal_pet ADD COLUMN IF NOT EXISTS diary_absence_started_at timestamptz;
ALTER TABLE zzal_pet ADD COLUMN IF NOT EXISTS diary_absence_awake_sec bigint NOT NULL DEFAULT 0;
ALTER TABLE zzal_pet ADD COLUMN IF NOT EXISTS diary_opportunity_at timestamptz;
ALTER TABLE zzal_pet ADD COLUMN IF NOT EXISTS diary_opportunity_consumed boolean NOT NULL DEFAULT false;
ALTER TABLE zzal_pet ADD COLUMN IF NOT EXISTS diary_language varchar(12) NOT NULL DEFAULT 'ko';
CREATE TABLE IF NOT EXISTS zzal_diary_entry (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pet_id bigint NOT NULL REFERENCES zzal_pet(id),
 opportunity_id varchar(120) NOT NULL UNIQUE,
 status varchar(20) NOT NULL CHECK(status IN ('RESERVED','GENERATING','READY','FAILED','UNCERTAIN')),
 created_at timestamptz NOT NULL, written_at timestamptz NOT NULL,
 ready_at timestamptz, read_at timestamptz,
 body text, preview varchar(300), language varchar(12) NOT NULL,
 source_snapshot_json text NOT NULL, source_hash varchar(64) NOT NULL, body_hash varchar(64),
 source_type varchar(40) NOT NULL DEFAULT 'DIARY_FICTION', prompt_version varchar(40) NOT NULL,
 claim_token varchar(80), claimed_at timestamptz, execution_receipt text,
 CONSTRAINT ck_diary_ready_body CHECK(status <> 'READY' OR (body IS NOT NULL AND length(trim(body)) > 0 AND ready_at IS NOT NULL)),
 CONSTRAINT ck_diary_read_ready CHECK(read_at IS NULL OR status='READY'),
 CONSTRAINT ck_diary_fiction CHECK(source_type='DIARY_FICTION')
);
-- Failed/uncertain execution also retains the slot until an explicitly authorized resolution.
CREATE UNIQUE INDEX IF NOT EXISTS uk_zzal_diary_single_slot ON zzal_diary_entry(pet_id) WHERE read_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_zzal_diary_history ON zzal_diary_entry(pet_id,written_at DESC,id DESC) WHERE status='READY';
