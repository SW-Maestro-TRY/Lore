-- PET action idempotency; existing pets and cursors are preserved.
CREATE TABLE zzal_action_receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id bigint NOT NULL REFERENCES zzal_pet(id),
    request_id uuid NOT NULL,
    action_kind varchar(32) NOT NULL,
    request_hash varchar(64) NOT NULL,
    response_version integer NOT NULL,
    result_json jsonb NOT NULL,
    completed_at timestamptz NOT NULL,
    CONSTRAINT uq_zzal_action_receipt_pet_request UNIQUE (pet_id, request_id),
    CONSTRAINT ck_zzal_action_receipt_response_version CHECK (response_version > 0),
    CONSTRAINT ck_zzal_action_receipt_hash CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_zzal_action_receipt_object CHECK (jsonb_typeof(result_json) = 'object')
);
