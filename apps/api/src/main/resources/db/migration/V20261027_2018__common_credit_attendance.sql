-- 목적: 매일 무료 크레딧을 7일 연속 출석으로 바꾼다.
--
-- ★ 표 하나를 새로 만든다. 옛 표는 건드리지 않는다.
-- credit_attendance — 「오늘 받기」를 누른 날 한 줄
--   day     한국 시각 날짜. (user_id, day) 가 유일이라 같은 날 두 번 눌러도 한 줄이다
--   streak  그날이 카드의 몇 일째인가(1~7). 전날 줄이 있으면 전날 + 1, 7 다음은 1, 없으면 1.
--           찍을 때 박아 둔다 — 나중에 규칙이 바뀌어도 이미 받은 사람의 카드는 안 바뀐다
-- 보상(4일째·7일째)은 이 표가 아니라 credit_event 에 REWARD 로 적힌다(refId attend-<카드 시작일>-d4 · -d7).

CREATE TABLE IF NOT EXISTS credit_attendance (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint  NOT NULL,
    day         date    NOT NULL,
    streak      integer NOT NULL,
    created_at  timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_credit_attendance_day UNIQUE (user_id, day)
);
