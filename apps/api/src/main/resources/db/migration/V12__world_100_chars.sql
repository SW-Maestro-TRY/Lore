-- 세계관 한 줄을 100자까지 담는다 (#192)


-- ── zzal_pet.world 를 varchar(40) → varchar(100) ────────────────────────
--
-- ★★ 무엇이 틀어져 있었나 — 같은 값의 상한이 세 곳에서 서로 달랐다.
--   캐릭터 정보 요청은 100자를 허용하고(@Size), 규칙 상수는 40자였고(WORLD_MAX_CHARS),
--   이 칸은 40자였다. 그래서 41~100자를 보내면 검증은 통과하고 INSERT 에서 터진다 —
--   사용자에게는 "입력이 길다" 가 아니라 그냥 500 으로 보인다.
--
-- ★ 제품 결정은 100자다. 상수와 칸을 그 값으로 맞춘다.
--
-- ★ 넓히기만 한다 — varchar 는 길이를 늘리는 것이 테이블 재작성 없이 끝나고
--   기존 값은 한 글자도 건드리지 않는다. 좁히는 방향이었다면 자르는 문제가 생기지만
--   여기는 그 반대다.

ALTER TABLE zzal_pet ALTER COLUMN world TYPE character varying(100);
