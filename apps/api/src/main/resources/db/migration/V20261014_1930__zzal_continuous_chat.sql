-- 대화시간/왕복제한과 기존 보상창을 분리. 기존 세션·턴 원문은 보존.
ALTER TABLE zzal_chat_session DROP CONSTRAINT zzal_chat_session_slot_check;
ALTER TABLE zzal_chat_session ADD CONSTRAINT zzal_chat_session_slot_check
    CHECK (slot IN ('BABY','MORNING','NOON','EVENING','CONTINUOUS'));
CREATE TABLE zzal_chat_reward (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id bigint NOT NULL,
    day_of date NOT NULL,
    slot varchar(10) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_zzal_chat_reward_window UNIQUE (pet_id,day_of,slot)
);
-- 부화일·slot의 기존 고유 제약과 함께 펫당 지속 세션 하나를 보장.
CREATE UNIQUE INDEX uk_zzal_chat_continuous_pet ON zzal_chat_session(pet_id) WHERE slot='CONTINUOUS';
-- 문맥/화면 이력은 필요한 페이지부터 읽는다. 대화가 길어져도 전체 턴 정렬을 피한다.
CREATE INDEX idx_zzal_chat_turn_pet_recent ON zzal_chat_turn(pet_id,created_at DESC,id DESC);
CREATE INDEX idx_zzal_chat_turn_pet_history ON zzal_chat_turn(pet_id,id DESC);
