-- Private support inquiries, separate from ratings, analytics and chat memory.
-- Historical owner/pet IDs follow zzal_motion_wish; deleting a pet must not erase its inquiry.
CREATE TABLE zzal_inquiry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    pet_id bigint,
    request_id uuid NOT NULL,
    body text NOT NULL,
    locale varchar(2) NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT uq_zzal_inquiry_owner_request UNIQUE (user_id, request_id),
    CONSTRAINT ck_zzal_inquiry_body CHECK (char_length(body) BETWEEN 1 AND 4000 AND body = btrim(body)),
    CONSTRAINT ck_zzal_inquiry_locale CHECK (locale IN ('ko', 'en', 'ja')),
    CONSTRAINT ck_zzal_inquiry_pet CHECK (pet_id IS NULL OR pet_id > 0)
);
