-- One durable claim per tutorial scene; prepare/GET never fabricates a USER turn.
CREATE TABLE zzal_stage_speech (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id bigint NOT NULL,
 pet_id bigint NOT NULL REFERENCES zzal_pet(id) ON DELETE CASCADE,
 intro_version integer NOT NULL,
 step varchar(24) NOT NULL,
 phase varchar(24) NOT NULL,
 status varchar(24) NOT NULL,
 claim_token uuid NOT NULL,
 input_snapshot text NOT NULL,
 input_hash varchar(64) NOT NULL,
 context_revision varchar(64) NOT NULL,
 expected_step varchar(32) NOT NULL,
 session_id bigint NOT NULL,
 line varchar(160),source varchar(24),motion_id varchar(40),turn_ref bigint,
 cost_trace text,failure_reason varchar(120),
 created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL,
 CONSTRAINT uk_zzal_stage_speech_beat UNIQUE(pet_id,intro_version,step,phase),
 CONSTRAINT ck_zzal_stage_speech_status CHECK(status IN ('PENDING','READY','FAILED','UNCERTAIN','SUPERSEDED'))
);
