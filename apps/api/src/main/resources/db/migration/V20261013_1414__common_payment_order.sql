-- ★ 표 하나를 새로 만든다. 옛 표는 건드리지 않는다.
-- payment_order
--   order_no     우리가 짓는 주문번호. 페이앱 var1 로 보내고 통보에서 그대로 돌아온다(추측 못 하는 값)
--   package_code 어느 상품인가(CreditPackage 이름). 금액·크레딧은 주문 때 값을 그대로 박아 둔다 —
--                상품표가 나중에 바뀌어도 이미 낸 사람의 주문 내용은 안 바뀐다
--   mul_no       페이앱 결제요청번호. 취소·대조할 때 쓴다
--   status       READY(결제창 열림) · WAITING(가상계좌 입금 대기) · PAID · CANCELLED(결제 전 취소)
--                · REFUNDED(결제 후 취소) · PARTIAL_REFUNDED(부분 취소 — 장부는 사람이 맞춘다)
--   구매자 휴대폰 번호는 **안 남긴다**. 페이앱이 필수로 받지만 우리는 넘기기만 한다.

CREATE TABLE IF NOT EXISTS payment_order (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      character varying(40)  NOT NULL,
    user_id       bigint                 NOT NULL,
    package_code  character varying(20)  NOT NULL,
    credits       integer                NOT NULL,
    amount        integer                NOT NULL,
    status        character varying(20)  NOT NULL,
    mul_no        character varying(40),
    pay_type      character varying(10),
    created_at    timestamp(6) with time zone NOT NULL,
    paid_at       timestamp(6) with time zone,
    cancelled_at  timestamp(6) with time zone,
    CONSTRAINT uk_payment_order_no UNIQUE (order_no),
    CONSTRAINT payment_order_status_check CHECK (status IN
        ('READY', 'WAITING', 'PAID', 'CANCELLED', 'REFUNDED', 'PARTIAL_REFUNDED'))
);

CREATE INDEX IF NOT EXISTS idx_payment_order_user ON payment_order (user_id, id);
