-- 튜토리얼 졸업(첫날 완주) 축하 창을 본 시각.
--
-- ★ 왜 서버가 드나 — 화면이 sessionStorage 로 기억하던 값이다. 탭을 새로 열거나 앱을 다시 켜면
--   그 기억이 사라져 <b>같은 축하 창이 다시 떴다</b>. 한 번 본 연출은 다시 나오지 않아야 하고,
--   그 판정은 기기·탭이 아니라 이 아이에 붙어야 한다(tutorial_step 을 서버가 드는 것과 같은 이유다).
--
-- ★ 불리언이 아니라 시각이다 — "봤다/안 봤다" 만 필요하지만 시각을 두면 "언제 처음 봤나" 도
--   같이 남는다. 칸 하나로 둘을 얻고, 나중에 "완주와 축하 사이가 얼마나 벌어지나" 를 볼 수 있다.
--   대신 <b>한 번 찍히면 안 움직인다</b>(엔티티가 비어 있을 때만 채운다).
--
-- ★ nullable 이어야 한다 — 이미 행이 있는 표다. NOT NULL 로 만들면 DB 가 조용히 거부하고
--   서버는 정상 기동한 채 실제 호출 때만 터진다(ZzalPet 의 컬럼 추가 규칙). 기존 아이는
--   null = "아직 안 봤다" 로 시작하는 것이 맞다.
--
-- ★ 번호가 V23 다음이 아니라 날짜다 — 여러 갈래가 동시에 번호를 집으면 같은 번호가 둘 나오고,
--   머지된 뒤에야 한쪽이 안 돈다. 날짜·시각은 겹치지 않는다. 값은 20260922.0100 이라
--   지금까지의 최대 번호(V23)보다 크다 — 순서가 뒤집히지 않는다.

