package com.lore.zzal.motion;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/**
 * 다 구운 움짤을 기계가 먼저 본다.
 *
 * <h3>지금은 아무것도 거르지 않는다</h3>
 * 실험의 게이트({@code gate.py} — 잘림·침범·빈 칸)는 실패를 가릴 수 있지만,
 * <b>"완벽" 과 "최적" 을 가르는 선은 아직 없다.</b> 그건 상훈님이 눈으로 하시던 판정이고,
 * 기하 게이트는 "물이 반대로 나감" 같은 의미 오류를 원리적으로 못 잡는다.
 *
 * 그래서 게이트가 충분히 강화될 때까지는 <b>세 판정 모두 상훈님 눈을 거치며</b>
 * 기준을 맞춰 간다(2026-09-03 지시). 여기서는 REVIEW 를 돌려 "사람이 봐야 함" 으로 두고,
 * 판정은 {@link ZzalMotion} 에 사람 판정과 나란히 쌓인다.
 *
 * <h3>버전을 남기는 이유</h3>
 * 게이트도 계속 좋아진다. 어느 버전이 내린 판정인지 모르면, 나중에 사람 판정과의
 * 일치율이 올랐을 때 게이트가 좋아진 건지 다른 게 바뀐 건지 못 가른다.
 *
 * <h3>★★ 붙일 자리 — 게이트 정의서(2026-09-11)의 3층 구조</h3>
 * 판정 기록 589건을 지표와 대조해 <b>왜 지금까지 안 맞았는지</b>가 나왔다:
 * <b>사람의 합격 기준은 "부드러움" 인데 게이트에는 부드러움 문턱이 아예 없었다.</b>
 * 실험 게이트는 전부 "잘렸나·겹쳤나·비었나" 만 본다. 서로 다른 것을 보고 있었으니 맞을 이유가 없었다.
 *
 * <pre>
 *   1층 즉시 실패   있고 없고라 기계가 정확히 잡는다 → 사람에게 안 올리고 다시 굽는다
 *                  잘림(0 초과) · 침범(진하기 28 · 8픽셀) · 빈 칸(5% 미만)
 *                  격자 구조(배율 1±0.1 밖) · 프레임 수(16 아님)
 *                  바닥선 편차(20px 초과) · 마크 잔존 · 중복(해시 일치)
 *
 *   2층 관문       앵커 · 크기. 합격작 43편의 90퍼센타일을 넘으면 <b>축 이름</b>을 붙여 올린다
 *                  ★ 여기서 실패시키지 않는다 — 앵커가 최악인데 합격으로 나온 판이 실제로 있다
 *                  ★ 회전·이동 동작에서는 이 층이 통째로 무효다(도는 게 정상인데 흔들림으로 잡힌다)
 *
 *   3층 합격 기준   부드러움. 적중률이 0.569(0.5 = 동전 던지기)라 <b>가장 약하다</b>
 *                  ★ 실패 판정에 쓰지 않고 "부드러움 의심" 이름표로만 쓴다
 * </pre>
 *
 * ★★ <b>기계는 "성공" 을 붙이지 않는다.</b> 합격 기준(부드러움)을 볼 줄 모르기 때문이다.
 *    약한 자로 실패를 선고하면 멀쩡한 결과물을 버린다 — 2픽셀 오차로 정상 결과 한 판을 통째로
 *    폐기하고 그 탓에 앞선 실험 결론까지 뒤집힌 적이 있다.
 *
 * ★ 2층·3층 출력이 <b>점수가 아니라 이름</b>인 것이 핵심이다. {@code 0.73점} 은 사람이 쓸 수 없지만
 *   "앵커 의심" 은 어디를 볼지 알려 준다.
 *
 * ★ 실제 측정은 <b>맥미니</b>가 한다(도구가 거기 있고, 판정하면서 그 자리에서 손봐야 한다).
 *   서버는 맥미니가 올린 판정을 받아 적기만 하면 된다 — {@code ZzalMotionCandidate.gateVerdict}.
 */
@Component
public class MotionGate {

    private final String version;

    public MotionGate(@Value("${app.zzal.gate-version:g0}") String version) {
        this.version = version;
    }

    /**
     * ★ g0 = 아직 아무것도 안 본다. 위 3층 구조를 붙일 자리가 여기다.
     *
     * ★★ 붙일 때도 <b>{@code PASS} 를 돌려주지 않는다.</b> 1층에 걸리면 {@code FAIL},
     *   나머지는 전부 {@code REVIEW} 다. "성공" 은 사람만 붙인다.
     */
    public Verdict judge(String imageKey) {
        return new Verdict(GateVerdict.REVIEW, "게이트 미적용(피팅 기간)", version);
    }

    public record Verdict(GateVerdict verdict, String note, String version) {
    }
}
