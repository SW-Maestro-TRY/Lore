package com.lore.zzal.bake;

/**
 * 일감 하나가 지나는 길(2차 명세 1장).
 *
 * <pre>
 *   BAKING ─ 게이트 성공 ────────────────→ JUDGING
 *      └─ 성공 아님 → REBAKING(3판 × 최대 2라운드) ─→ JUDGING
 *   JUDGING ─ 합격 ─→ PUBLISH_WAIT ─(다음 기상)→ PUBLISHED
 *      └─ 전부 불합격 ─→ HOLD
 * </pre>
 *
 * <h3>★ PUBLISH_WAIT 가 따로 있는 이유</h3>
 * 판정이 낮에 끝나도 그 자리에서 주지 않는다. <b>판정이 끝난 뒤 처음 맞는 기상</b>까지 기다린다
 * (정본 16장) — "자는 동안 연습해서 아침에 배워 왔다" 는 이야기를 지키기 위해서다.
 *
 * <h3>★ HOLD 는 자동으로 안 풀린다</h3>
 * 후보가 전부 아니면 그건 판이 나쁜 게 아니라 지시문이나 원본에 문제가 있다는 신호다.
 * 같은 조건으로 또 구우면 또 같은 것이 나온다. 사람이 도구를 고친 뒤 다시 꺼낸다.
 */
public enum BakeStatus {

    /** 서버가 API 로 1판을 굽는 중 */
    BAKING,
    /** 맥미니가 CLI 로 다시 굽는 중 */
    REBAKING,
    /** 사람 판정을 기다린다 — 그때까지 나온 후보가 전부 달려 있다 */
    JUDGING,
    /** 합격했고 공개할 기상을 기다린다 */
    PUBLISH_WAIT,
    /** 사용자에게 갔다 */
    PUBLISHED,
    /** 후보가 전부 불합격 — 사람이 다시 꺼내기 전까지 멈춘다 */
    HOLD
}
