package com.lore.zzal.pet;

/**
 * 지금 자고 있다면 어떤 잠인가(정본 2·12장).
 *
 * 둘은 창·길이·리셋이 다르다 — 밤잠은 19~23시에 들어 07~10시에 깨고 <b>하루의 경계</b>다.
 * 낮잠은 아기 60분 안에 한 번, 5분 뒤 깨우기·10분 뒤 자동 기상이며 경계가 아니다(카운터 유지).
 * 둘 다 재우기·깨우기 횟수(2층 11번 조건)에는 들어간다.
 */
public enum SleepKind {

    /** 밤잠. 19:00~23:00 재우기(23:00 자동), 07:00~10:00 깨우기(10:00 자동 = 늦잠). */
    NIGHT,

    /** 낮잠(12장 40분). 아기 60분 안에 한 번. 5분 뒤 깨우기 켜짐, 10분 뒤 자동 기상. */
    NAP
}
