package com.lore.zzal.motion;

/**
 * 모션 한 개가 지금 어디까지 왔나.
 *
 * ★ "구웠는가" 와 "보여줘도 되는가" 는 다른 질문이다. 다 구웠는데 게이트에 걸린 것,
 *   보여주고 있지만 상훈님 확인은 아직인 것이 따로 있어야 한다.
 */
public enum MotionStatus {

    /** 굽는 중. 사용자에게 안 보인다. */
    PENDING,

    /** 다 구워져 사용자에게 보이는 중. */
    OPEN,

    /** 끝내 못 구웠다. 사용자에게 안 보인다. */
    FAILED
}
