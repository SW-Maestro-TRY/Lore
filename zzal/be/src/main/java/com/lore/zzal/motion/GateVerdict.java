package com.lore.zzal.motion;

/**
 * 자동 게이트의 판정.
 *
 * ⚠️ 지금은 이 판정만으로 노출을 정하지 않는다. 게이트가 아직 강화 중이라
 *    <b>세 값 모두 상훈님 눈을 거치며</b> 기준을 맞춰 가는 기간이다(2026-09-03 지시).
 *    {@link HumanVerdict} 와 나란히 쌓아 일치율이 오르면 그때 자동으로 넘긴다.
 */
public enum GateVerdict {

    /** 통과. 원래대로면 판정 없이 바로 지급해도 되는 것. */
    PASS,

    /** 애매하다. 사람 눈이 필요하다. */
    REVIEW,

    /** 실패. 다시 구워야 한다. */
    FAIL
}
