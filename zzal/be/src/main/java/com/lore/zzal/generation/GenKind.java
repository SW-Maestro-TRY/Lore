package com.lore.zzal.generation;

/**
 * 무엇을 굽는 작업인가.
 *
 * ★ 부화와 모션이 같은 표를 쓴다. 하는 일이 같기 때문이다 — 굽고, 실패하면 다시 하고, 돈이 나간다.
 *   나누면 재시도·타임아웃 로직을 두 벌 쓰게 되고, "이 사용자에게 총 얼마 썼나" 를 셀 때
 *   매번 두 표를 더해야 한다(한쪽을 빠뜨리면 원가가 과소 집계된다).
 *
 *   검수는 이 표의 일이 아니다. 모션의 노출 여부는 zzal_motion 의 status 가 담당한다.
 */
public enum GenKind {

    /** 부화 — 2프레임 8상태. 자동으로 돌고 사용자에게 바로 지급된다. */
    HATCH,

    /** 모션 — 16프레임 고급 동작. 상훈님 검수를 거쳐야 지급된다. */
    MOTION
}
