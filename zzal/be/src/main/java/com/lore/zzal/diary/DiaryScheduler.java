package com.lore.zzal.diary;
import com.lore.zzal.pet.*;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Component;
import org.springframework.data.domain.PageRequest;
import java.time.*;

/** Explicitly disabled by default. A real or test model is injected only after activation. */
@Component
@ConditionalOnProperty(name="zzal.diary.enabled",havingValue="true")
public class DiaryScheduler {
    private final ZzalPetRepository pets;
    private final DiaryEntryRepository entries;
    private final DiaryService diary;
    private final DiaryWorkerTransactions tx;
    private final ObjectProvider<DiaryModel> models;
    public DiaryScheduler(ZzalPetRepository pets,DiaryEntryRepository entries,DiaryService diary,DiaryWorkerTransactions tx,ObjectProvider<DiaryModel> models){
        this.pets=pets;this.entries=entries;this.diary=diary;this.tx=tx;this.models=models;
    }
    @Scheduled(fixedDelayString="${zzal.diary.sweep-ms:30000}",scheduler="diaryTaskScheduler")
    public void sweep(){
        // A missing adapter must not leave fake generated content or reserve entries indefinitely.
        DiaryModel model=models.getIfAvailable();if(model==null)return;
        Instant now=Instant.now();tx.recoverUncertain(now.minus(Duration.ofMinutes(10)));
        pets.findByPhase(PetPhase.ALIVE).forEach(p->diary.reserveDue(p.getId(),now));
        entries.findByStatusOrderByIdAsc(DiaryEntry.Status.RESERVED,PageRequest.of(0,20)).forEach(e->run(e.id(),model));
    }
    public void run(Long id,DiaryModel model){
        var claim=tx.claim(id,Instant.now());if(claim.isEmpty())return;
        var c=claim.get();
        DiaryModel.Result result;
        try{result=model.generate(c.snapshot(),c.language(),DiaryPrompt.SYSTEM);
            if(result==null)result=new DiaryModel.Result(null,"Empty provider response");}
        catch(Exception ex){tx.uncertain(c,ex instanceof DiaryModel.ExecutionUncertain uncertain?uncertain.receipt():"Provider outcome unknown: "+ex.getClass().getSimpleName());return;}
        try{tx.finish(c,result,Instant.now());}
        catch(Exception persistence){
            // Reuse the exact generated bytes; never repeat a model call after a save failure.
            try{tx.finish(c,result,Instant.now());}
            catch(Exception again){tx.uncertain(c,"Generated result awaiting authorized resolution; receipt="+result.executionReceipt()+"; body="+result.body());}
        }
    }
}
