package com.lore.zzal.motion;

/**
 * 동작이 어느 층에 속하나(정본 6·13장).
 *
 * 층은 "언제 열리나" 를 가른다. 기본 행동(2프레임)은 1층이 부화 즉시, 2층이 행동 조건으로 열리고,
 * 심화 행동(16프레임)은 층과 무관하게 열린 동작을 13장 번호 순으로 밤에 굽는다.
 * 선물은 그 순서 밖의 특별 동작이다.
 */
public enum MotionLayer {

    /** 격자 1장 = 1~8번. 부화 직후 전부 열림. */
    BASIC_1,

    /** 격자 2장 = 9~16번. 동작마다 행동 조건. 충족 즉시 "○○를 배웠어요" + 폭죽. */
    BASIC_2,

    /** 카탈로그 밖 특별 1종씩(101 구르기·102 뒤로 넘어짐). 기본 행동 없이 심화 행동만 있다. */
    GIFT
}
