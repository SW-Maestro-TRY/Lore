package com.lore.zzal.bake;

/**
 * 게이트가 후보 한 판을 셋 중 하나로 가른다(정본 6장).
 *
 * <h3>★ "완벽" 이라는 말을 안 쓴다</h3>
 * 1.9 에서 이름을 {@code SUCCESS} 로 정했다. 기계가 "완벽" 을 판정할 수 있다는 인상을 주면
 * 그 판정을 믿게 되고, 지금은 믿지 않기로 했다.
 *
 * <h3>★ 셋 다 사람에게 보인다</h3>
 * {@code SUCCESS} 도 자동으로 통과시키지 않는다. 게이트는 <b>거르는 일</b>만 하고
 * <b>정하는 일</b>은 사람이 한다. 기준이 사람 눈과 맞는지 아직 모르기 때문이다.
 */
public enum BakeGateVerdict {

    /** 정말 완벽할 때만 */
    SUCCESS,
    /** 애매 — 가운데가 넓어지는 것을 받아들인다 */
    NEEDS_REVIEW,
    /** 명백히 망가졌다(잘림 · 프레임 수 안 맞음 따위) */
    FAIL
}
