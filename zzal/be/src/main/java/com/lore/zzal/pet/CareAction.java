package com.lore.zzal.pet;

/**
 * 돌봄 버튼 6종(정본 4·5장).
 *
 * ★ 경로를 여섯으로 나누지 않고(`/feed`·`/snack`…) 이 값을 받는 하나로 둔 이유 —
 *   규칙이 한 곳에 모여야 "밥은 되는데 간식만 판정이 다른" 일이 안 생기고, 자는 중·여행 중·아픔 같은
 *   공통 거절이 한 문에서 걸린다.
 */
public enum CareAction {

    /** 밥. 배부름 +1, 재고 -1. 가득이면 거부. */
    FEED,

    /** 간식. 행복 +1. 연속 5개면 배탈. 아프면 거부. */
    SNACK,

    /** 쓰다듬기. 행복 0, 친밀도 +5(하루 3회). 거부 없음. */
    PET,

    /** 청소. 흔적 0. 깨끗하면 거부. */
    CLEAN,

    /** 목욕. 흔적 0 + 행복 +1. 하루 1회. */
    BATH,

    /** 약. 병 즉시 치료. 안 아프면 거부. */
    MEDICINE
}
