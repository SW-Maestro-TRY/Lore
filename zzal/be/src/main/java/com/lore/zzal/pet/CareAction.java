package com.lore.zzal.pet;

/**
 * 돌봄 버튼 하나하나.
 *
 * ★ 경로를 셋으로 나누지 않고(`/feed`·`/pet`·`/clean`) 이 값을 받는 하나로 둔 이유 —
 *   규칙이 한 곳에 모여야 "밥은 되는데 쓰다듬만 판정이 다른" 일이 안 생기고,
 *   나중에 간식 같은 것이 붙어도 주소가 늘지 않는다.
 */
public enum CareAction {

    /** 밥. 포만감이 오르고 쓰레기가 하나 는다. */
    FEED,

    /** 쓰다듬. 행복이 오른다. */
    PET,

    /** 청소. 쌓인 것을 한 번에 치운다. */
    CLEAN
}
