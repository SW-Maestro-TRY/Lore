package com.lore.zzal.pet;

/** 펫이 FAILED·DEAD 가 된 이유. 살아 있으면 비어 있다. */
public enum DeathReason {

    /** 부화 실패 — 생성이 끝내 안 됐다. */
    HATCH_FAILED,

    /** 방치로 죽음 — 아직 규칙 없음. 나중에 쓸 자리. */
    NEGLECTED,

    /**
     * 주인이 직접 보냈다(놓아주기).
     *
     * ★ 방치나 실패가 아니라 <b>주인이 스스로 보낸 것</b>이라 따로 갈라 둔다.
     *   NEGLECTED 와 합쳐 두면 나중에 "얼마나 방치되는가" 를 볼 때 스스로 보낸 아이가
     *   섞여 들어와 지표가 통째로 거짓말을 하게 된다. 화면에서 할 말도 다르다 —
     *   "굶어서 떠났어요" 와 "잘 보내 줬어요" 는 같은 문구를 쓸 수 없다.
     */
    RELEASED
}
