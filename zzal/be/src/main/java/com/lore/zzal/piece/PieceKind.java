package com.lore.zzal.piece;

/**
 * 조각 네 칸(정본 6장). 화면의 4칸 도장이 이 순서다.
 *
 * <h3>★ 순서가 뜻을 갖는다</h3>
 * 기분 좋은 날의 선물은 <b>아직 안 찬 것 중 앞선 것</b>을 채운다(정본 6장). 그래서 이 enum 의
 * 선언 순서가 곧 "앞선 것" 의 정의다. 순서를 바꾸면 선물이 다른 칸을 채운다.
 */
public enum PieceKind {

    /** 밥 조각 */
    FOOD,
    /** 놀이 조각 */
    PLAY,
    /** 청결 조각 */
    CLEAN,
    /** 교감 조각 */
    BOND
}
