package com.lore.zzal.pet;

/**
 * 왜 아픈가(정본 5장). 화면에는 "아픈 자세 + 해골" 하나로만 보이고, 이 값은 <b>왜 그렇게 됐는지</b>를 남긴다.
 *
 * ★ 한 칸으로 뭉치지 않는 이유 — 나중에 "무엇 때문에 아픈 사람이 많은가" 를 세어야 규칙을 손볼 수 있다.
 *   전부 SICK 하나면 "간식을 너무 줘서" 와 "굶겨서" 가 같은 숫자로 섞여, 어느 쪽을 고칠지 못 정한다.
 */
public enum SickKind {

    /** 방치 — 케어 미스 누적이 홀수가 되는 순간 30%. */
    NEGLECT,

    /** 더러움 — 흔적 4개인 채로 깨어 있는 6시간(100%). */
    DIRTY,

    /** 배탈 — 다른 행동 없이 간식 5개 연속(100%). */
    UPSET,

    /** 자연 발병 — 심화 행동이 열린 뒤 깨어 있는 3일 안에 한 번(정본 5·16장). */
    NATURAL
}
