-- 다 만들어지면 이메일로 알리기 위해, 「어디로」와 「보냈나」를 적을 칸을 단다.
--
-- ── 왜 필요한가 ─────────────────────────────────────────────────────
-- 한 편에 5~15분이 걸린다. 그동안 화면이 사람을 붙들고 있고, 창을 닫으면
-- 다 됐는지 알 길이 없다. 게스트는 더 나쁘다 — 자기 작품을 브라우저 uid 로만
-- 찾으므로, 다른 기기로 들어오면 만든 것을 영영 못 본다. 메일에 담는 결과
-- 링크가 그 사람이 자기 작품으로 돌아오는 유일한 길이다.
--
-- ── 왜 계정 이메일을 베껴 두지 않나 ────────────────────────────────
-- 로그인한 사람의 주소는 이 칸이 비어 있고, 보낼 때 users 에서 읽는다.
-- 베껴 두면 사람이 계정 이메일을 바꾼 뒤에도 옛 주소로 나간다. 이 칸은
-- **로그인 안 한 사람이 직접 적어 넣은 주소** 전용이다.
--
-- ★ 번호는 도메인이 같이 쓰는 한 줄이다. 새 마이그레이션을 만들 때는
--   이 폴더와 `apps/api/.../db/migration` 을 둘 다 보고 다음 번호를 잡는다.
--   (2026-09-14: 원래 V12 였는데, apps/api 가 같은 번호로 먼저 develop 에
--   들어가 있어서 배포가 "Found more than one migration with version 12"
--   로 죽었다. V16(그때 두 폴더의 최댓값 다음)으로 옮겼다 — 이 파일은 그
--   배포 실패 전까지 한 번도 적용된 적이 없어서 옮겨도 안전했다.)

-- 게스트가 적어 넣은 주소. 로그인한 사람은 비어 있다(users 에서 읽는다).
-- 안 적으면 안 보낸다 — 이건 선택이지 조건이 아니다.
ALTER TABLE webtoon_job ADD COLUMN IF NOT EXISTS notify_email VARCHAR(255);

-- 보낸 때. **이 칸이 두 번 보내는 것을 막는다.**
-- 끝나는 자리가 여럿이고(다 됨 · 실패 · 되살리기) 화면은 0.8초마다 묻는다 —
-- 안 적으면 같은 사람에게 같은 메일이 여러 통 나간다.
ALTER TABLE webtoon_job ADD COLUMN IF NOT EXISTS notified_at TIMESTAMPTZ;
