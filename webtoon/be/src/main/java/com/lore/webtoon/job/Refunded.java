package com.lore.webtoon.job;

/**
 * 만들기가 실패했을 때 <b>실제로 무엇을 돌려줬나.</b>
 *
 * 화면이 실패 안내에서 마지막 한 줄을 이걸로 고른다. 로그인한 사람에게는
 * 크레딧을, 게스트에게는 오늘의 무료 횟수를 돌려주므로 같은 말을 쓸 수 없다 —
 * 크레딧이 없는 사람에게 "크레딧을 환불했어요" 라고 적으면, 없는 것을
 * 돌려줬다는 말이라 아무 뜻이 없다.
 *
 * <b>돌려준 뒤에 정한다.</b> 전에는 "돌려줄 사람이 있었나"(로그인했나 ·
 * 게스트 열쇠가 있나)로 적었는데, 그건 돌려줬다는 뜻이 아니다 — 돌려주는
 * 일이 조용히 실패해도 화면에는 "돌려드렸어요" 가 그대로 떴다.
 */
public enum Refunded {

    /** 계정 크레딧을 돌려줬다. */
    CREDIT("credit"),

    /** 오늘의 무료 횟수를 되돌렸다. */
    FREE("free"),

    /** 돌려준 것이 없다 — 낸 적이 없거나, 돌려주다 실패했다. */
    NONE("none");

    private final String wire;

    Refunded(String wire) {
        this.wire = wire;
    }

    /** 화면이 읽는 값. */
    public String wire() {
        return wire;
    }
}
