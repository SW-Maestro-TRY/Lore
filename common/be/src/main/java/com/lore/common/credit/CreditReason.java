package com.lore.common.credit;

/**
 * 크레딧이 왜 움직였나.
 *
 * 이름을 그대로 DB 에 적는다(순서 번호가 아니라). 순서로 적으면 나중에 사이에
 * 하나를 끼워 넣는 순간 옛 줄의 뜻이 통째로 바뀐다 — 돈에 준하는 기록에서는
 * 절대 안 된다.
 */
public enum CreditReason {

    /** 가입하고 처음 받는 몫. 계정마다 딱 한 번. */
    WELCOME("가입 축하 크레딧"),

    /** 날마다 받는 몫. */
    DAILY("오늘의 무료 크레딧"),

    /** 결제로 받은 몫. 결제 붙이기는 아직이다(#155) — 이유만 먼저 둔다. */
    PURCHASE("크레딧 충전"),

    /** 만들면서 쓴 몫. */
    /* 어디서 썼는지는 CreditDomain 이 맡고, 이유는 성격만 말한다. */
    SPEND("사용"),

    /**
     * 시작조차 못 했을 때 돌려주는 몫.
     *
     * 뺀 줄을 지우는 것이 아니라 반대 줄을 하나 더 적는다 — 지우면 원래 얼마를
     * 냈는지가 사라진다.
     */
    REFUND("만들지 못해 돌려드림"),

    /**
     * 서비스를 써 보게 하려고 주는 몫 — <b>온보딩·공유·홍보 같은 활동 보상.</b>
     *
     * 무엇을 주는지는 <b>서비스마다 다르게 정한다</b>(팀 결정). 그래서 이유는
     * "활동 보상" 하나로 두고, 어느 서비스인지는 {@link CreditDomain} 이,
     * 무슨 활동인지는 {@code memo} 가 말한다 — 여기에 활동 종류를 계속
     * 늘리면 서비스가 하나 붙을 때마다 이 파일을 고쳐야 한다.
     *
     * <b>같은 활동을 두 번 주지 않는 것은 {@code refId} 가 맡는다.</b>
     * 활동을 가리키는 값을 그대로 넣는다 — 예: {@code "onboarding"},
     * {@code "share-2026-09"}. 유일키가 (계정, 이유, refId) 라, 같은 값으로
     * 두 번 불러도 한 번만 들어간다.
     */
    REWARD("활동 보상"),

    /** 사람이 손으로 맞춘 몫. 왜 그랬는지는 memo 에 적는다. */
    ADJUST("직접 조정");

    private final String label;

    CreditReason(String label) {
        this.label = label;
    }

    /** 화면의 「내역」에 그대로 나가는 말. */
    public String label() {
        return label;
    }
}
