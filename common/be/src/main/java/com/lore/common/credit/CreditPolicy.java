package com.lore.common.credit;

/**
 * 크레딧의 <b>값</b> — 팀이 정한 기준 하나를 여기 둔다.
 *
 * <h2>1 크레딧 = 200원</h2>
 *
 * 서비스마다 "한 편 12크레딧" 처럼 자기 값을 정하는데, 그 값이 실제로
 * 얼마인지를 아는 곳이 없으면 서비스끼리 크레딧의 무게가 달라진다 —
 * 같은 1크레딧이 웹툰에서는 200원어치이고 짤에서는 50원어치가 되면,
 * 한 지갑을 쓰는 뜻이 사라진다.
 *
 * <h2>이 값은 아직 추정이다</h2>
 *
 * 장당 원가 200원은 <b>실측 전 어림값</b>이다. 실제로 재 보면 한 편(6장)에
 * 1,000원 안팎이 나오는데 12크레딧이면 2,400원어치라, 지금은 <b>넉넉히 주는
 * 쪽</b>으로 벌어져 있다. 그렇게 두는 것이 지금 방침이다 — 크레딧이 모자라
 * 화면을 못 보는 일이 없게 하고, 실제 원가가 쌓이면 그때 값을 정한다.
 *
 * 그래서 이 상수는 <b>화면에 원 단위를 보여 줄 때</b>와 <b>지출을 견줄 때</b>
 * 쓰는 기준이지, 지금 당장 과금하는 값이 아니다.
 *
 * <h2>정책은 서비스가 정한다</h2>
 *
 * 무엇에 얼마를 받고 무엇으로 얼마를 주는지는 <b>서비스마다 다르다</b>(팀
 * 결정). 공통은 장부와 규칙만 갖는다 —
 *
 * <ul>
 *   <li>같은 일로 두 번 주거나 받지 않는다 ({@code refId} 유일키)</li>
 *   <li>모자라면 아예 안 뺀다</li>
 *   <li>돌려주는 양은 낸 만큼만, 장부가 정한다</li>
 * </ul>
 *
 * 아직 안 정한 것: 일일 지급 한도, 서비스 간 중복 보상 조정(초기에는 허용),
 * 환불 시 처리, 비정상 획득 제한.
 */
public final class CreditPolicy {

    /** 1 크레딧이 얼마인가. 팀이 정한 기준값(2026-09-08). */
    public static final int KRW_PER_CREDIT = 200;

    /** 크레딧 -> 원. 화면에 "약 2,400원" 처럼 보여 줄 때 쓴다. */
    public static long toKrw(int credits) {
        return (long) credits * KRW_PER_CREDIT;
    }

    private CreditPolicy() {
    }
}
