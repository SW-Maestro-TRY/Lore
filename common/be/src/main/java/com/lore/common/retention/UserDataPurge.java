package com.lore.common.retention;

/**
 * 탈퇴한 사람의 데이터를 자기 도메인에서 지우는 자리.
 *
 * <h2>왜 인터페이스인가</h2>
 *
 * 계정은 {@code common} 이 들고 있지만 그 사람이 만든 것은 도메인마다 흩어져
 * 있다(웹툰 작품, 캐릭터, 짤 펫 …). {@code common} 이 각 도메인의 표를 직접
 * 알면 <b>의존 방향이 뒤집힌다</b> — 이 저장소는 {@code common ← 도메인}
 * 한 방향으로만 기대는 관례를 지킨다.
 *
 * 그래서 {@code common} 은 "지울 때가 됐다" 고 부르기만 하고, 무엇을 어떻게
 * 지울지는 각 도메인이 자기 패키지 안에서 정한다. 도메인이 하나 늘어도
 * {@link AccountPurge} 는 안 고친다.
 *
 * <h2>구현이 지켜야 할 것</h2>
 *
 * <ul>
 *   <li><b>여러 번 불려도 괜찮아야 한다.</b> 앞선 회차가 중간에 끊기면 다음
 *       날 다시 불린다. 이미 지운 것에 또 불려도 조용히 0 을 돌려준다.</li>
 *   <li><b>S3 객체를 먼저 지운다.</b> DB 행을 먼저 지우면 어느 키를 지워야
 *       하는지 알 길이 사라져서, 그림이 영영 남는다.</li>
 *   <li><b>예외를 밖으로 내보내도 된다.</b> {@link AccountPurge} 가 사람
 *       단위로 잡아 기록하고 다음 사람으로 넘어간다 — 한 사람의 데이터가
 *       이상해서 나머지 전부가 안 지워지는 일은 없어야 한다.</li>
 * </ul>
 */
public interface UserDataPurge {

    /** 기록에 적을 이름. 어느 도메인이 무엇을 지웠는지 로그로 알아보려고 쓴다. */
    String domain();

    /**
     * 이 사람의 것을 지운다.
     *
     * @return 지운 행 수. 기록용이라 정확한 합계일 필요는 없고, 0 이면 "지울
     *         것이 없었다" 는 뜻이다.
     */
    int purge(Long userId);
}
